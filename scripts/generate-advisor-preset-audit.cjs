#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");
const catalog = require("../packages/advisor/catalog.js");

const root = path.resolve(__dirname, "..");
const outputPath = path.join(root, "docs/0004_advisor-preset-path-audit.md");

function md(value) {
  return String(value || "").replace(/\|/g, "\\|").replace(/\r?\n/g, "<br>");
}

function mermaid(value) {
  return String(value || "").replace(/"/g, "'").replace(/\r?\n/g, " ");
}

function nodeId(value) {
  return String(value).replace(/[^a-zA-Z0-9_]/g, "_");
}

function buildDocument() {
  const replyCount = catalog.fixedAnswers.reduce((sum, item) => sum + (item.suggestedReplies || []).length, 0);
  const lines = [
    "<!-- Generated by scripts/generate-advisor-preset-audit.cjs. Edit packages/advisor/catalog.js, then regenerate. -->",
    "# Lumino 首页顾问：预制问答路径与默认答案审计",
    "",
    `- 内容版本：\`${catalog.contentVersion}\``,
    `- 一级预制问题：${catalog.topics.length} 个`,
    `- 二级选择与确定性答案：${replyCount} 条`,
    `- 工具直达路径：${catalog.toolRoutes.length} 条（CN Code）`,
    "- 执行原则：点击预制问题或二级选择时只读取本地目录，不调用模型；只有用户自由输入且未命中固定意图时，才进入检索或模型路径。",
    "",
    "## 完整路径图",
    "",
    "```mermaid",
    "flowchart LR",
    "  START([进入官网，顾问自动展开]) --> TOPICS{选择预制问题}",
  ];

  for (const record of catalog.fixedAnswers) {
    const topic = catalog.topics.find((item) => item.id === record.topicId);
    const tid = `T_${nodeId(record.topicId)}`;
    const end = `E_${nodeId(record.topicId)}`;
    lines.push(`  TOPICS --> ${tid}[\"${mermaid(topic?.label.zh || record.topicId)}\"]`);
    lines.push(`  ${end}([\"专属固定答案 + 资料 + CTA\"])`);
    for (const option of record.suggestedReplies || []) {
      const rid = `R_${nodeId(record.topicId)}_${nodeId(option.id)}`;
      lines.push(`  ${tid} --> ${rid}[\"${mermaid(option.label.zh)}\"] --> ${end}`);
    }
  }
  lines.push("  FREE[用户自由输入] --> CN{命中 CN / HS / TARIC 意图?}");
  lines.push("  CN -->|是| TOOL[CN Code 工具说明 + 试算器 + 编码指南 + 人工复核]");
  lines.push("  CN -->|否| RETRIEVAL[受控检索 / 模型回答或安全兜底]");
  lines.push("```", "", "## 逐项答案核对", "");

  for (const record of catalog.fixedAnswers) {
    const topic = catalog.topics.find((item) => item.id === record.topicId);
    lines.push(`### ${topic?.label.zh || record.topicId}`, "");
    lines.push(`- 路径 ID：\`${record.topicId}\``);
    lines.push(`- 一级默认答案：${record.answer.zh}`);
    lines.push(`- 追问：${record.nextQuestion.zh}`);
    lines.push(`- 资料：${(record.sourceIds || []).map((id) => `\`${id}\``).join("、")}`);
    lines.push(`- CTA：${record.cta.label.zh}（\`${record.cta.url}\`）`, "");
    lines.push("| 用户选择 | Reply ID | 对应默认答案 |", "|---|---|---|");
    for (const option of record.suggestedReplies || []) {
      const outcome = catalog.replyOutcomes?.[record.topicId]?.[option.id];
      if (!outcome) throw new Error(`Missing outcome: ${record.topicId}.${option.id}`);
      lines.push(`| ${md(option.label.zh)} | \`${option.id}\` | ${md(outcome.zh)} |`);
    }
    lines.push("");
  }

  lines.push("## CN Code 工具直达路径", "");
  for (const route of catalog.toolRoutes) {
    lines.push(`- 意图：\`${route.intent}\``);
    lines.push(`- 默认答案：${route.answer.zh}`);
    lines.push(`- 入口：${route.links.map((item) => `${item.label.zh}（\`${item.url}\`）`).join("；")}`);
    lines.push(`- 资料：${(route.sourceIds || []).map((id) => `\`${id}\``).join("、")}`, "");
  }

  lines.push(
    "## 完整性门槛",
    "",
    "发布前必须同时满足：",
    "",
    "1. 每个一级问题都有中英文固定答案、追问、资料和 CTA。",
    "2. 每个可见二级选择都有独立的中英文默认答案，不允许使用统一的“已记录”占位话术。",
    "3. 所有预制路径的响应模式均为 `fixed`，并在本地完成，不进入模型调用。",
    "4. 每个二级选择都是有资料与 CTA 的终点，不出现空节点或死路。",
    "5. CN Code 查询优先返回现有工具与核对指南，不由模型作出正式归类认定。",
    "6. 本文件必须由目录重新生成并通过 `--check`，避免文档与运行时内容漂移。",
    ""
  );
  return lines.join("\n");
}

const generated = buildDocument();
if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, generated, "utf8");
  console.log(`Wrote ${path.relative(root, outputPath)}`);
} else if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error("Advisor preset audit is out of date. Run: node scripts/generate-advisor-preset-audit.cjs --write");
    process.exit(1);
  }
  console.log("Advisor preset audit is current.");
} else {
  process.stdout.write(generated);
}
