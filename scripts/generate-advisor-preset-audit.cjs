#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");
const catalog = require("../packages/advisor/catalog.js");

const root = path.resolve(__dirname, "..");
const outputPath = path.join(root, "docs/0004_advisor-preset-path-audit.md");
const topicPurpose = Object.freeze({
  cbam_scope: "核对产品信息、CN Code 与 CBAM 覆盖范围，不替代正式归类",
  cbam_data_start: "把进口商要求转成可执行的数据边界与最小资料清单",
  cbam_vs_pcf: "区分 CBAM 与 PCF 的用途、边界和可复用底账",
  pcf_data_start: "确定功能单位、系统边界、最小采集清单与热点解释",
  esg_ghg: "辨别 ESG 报告、问卷、组织盘查和 Scope 数据交付物",
  inventory_first_year: "从组织边界、Scope 1/2 和重点 Scope 3 启动首年盘查",
  eudr_csddd: "区分商品追溯证据与企业尽职管理证据",
  renewable_power: "按目标、用电与凭证要求规划绿电、绿证和自建组合",
  service_triage: "根据提出方、交付物与时限匹配主服务",
});
const linkTypeName = Object.freeze({ tool: "合规工具", knowledge: "知识指南", contact: "人工复核" });

function md(value) {
  return String(value || "").replace(/\|/g, "\\|").replace(/\r?\n/g, "<br>");
}

function mermaid(value) {
  return String(value || "").replace(/"/g, "'").replace(/\r?\n/g, " ");
}

function nodeId(value) {
  return String(value).replace(/[^a-zA-Z0-9_]/g, "_");
}

function buildDocument() {
  const replyCount = catalog.fixedAnswers.reduce((sum, item) => sum + (item.suggestedReplies || []).length, 0);
  const answerNodeCount = catalog.fixedAnswers.length + replyCount + catalog.toolRoutes.length;
  const missingBilingual = [];
  for (const record of catalog.fixedAnswers) {
    if (!record.answer?.zh || !record.answer?.en) missingBilingual.push(record.topicId);
    for (const option of record.suggestedReplies || []) {
      const outcome = catalog.replyOutcomes?.[record.topicId]?.[option.id];
      if (!outcome?.zh || !outcome?.en) missingBilingual.push(`${record.topicId}.${option.id}`);
    }
  }
  for (const route of catalog.toolRoutes) {
    if (!route.answer?.zh || !route.answer?.en) missingBilingual.push(route.intent);
  }
  if (missingBilingual.length) throw new Error(`Missing bilingual content: ${missingBilingual.join(", ")}`);
  const lines = [
    "<!-- Generated by scripts/generate-advisor-preset-audit.cjs. Edit packages/advisor/catalog.js, then regenerate. -->",
    "# Lumino 首页顾问：预制问答内容总结与路径审计",
    "",
    `- 内容版本：\`${catalog.contentVersion}\``,
    `- 一级预制问题：${catalog.topics.length} 个`,
    `- 二级选择与确定性答案：${replyCount} 条`,
    `- CN Code 意图路径：${catalog.toolRoutes.length} 条，包含 3 个入口（试算器、编码指南、人工复核）`,
    `- 中英文答案覆盖：${answerNodeCount}/${answerNodeCount}，缺失 0 条`,
    "- 执行原则：点击预制问题或二级选择时只读取本地目录，不调用模型；只有用户自由输入且未命中固定意图时，才进入检索或模型路径。",
    "",
    "## 内容总览",
    "",
    "这套预制内容面向不熟悉法规字段的出口、外贸、关务、采购、生产、财务和 EHS 人员。用户先选择最接近的问题，再用一个业务事实完成第二层判断；系统返回专属固定答案、资料来源和下一步入口。",
    "",
    "| 一级预制问题 | 回答目标 | 二级选择 | 完成入口 |",
    "|---|---|---|---|",
  ];

  for (const record of catalog.fixedAnswers) {
    const topic = catalog.topics.find((item) => item.id === record.topicId);
    const choices = (record.suggestedReplies || []).map((item) => item.label.zh).join("；");
    lines.push(`| [${md(topic?.label.zh || record.topicId)}](#path-${record.topicId}) | ${md(topicPurpose[record.topicId])} | ${md(choices)} | ${md(record.cta.label.zh)} |`);
  }

  lines.push(
    "",
    "## 公开名称",
    "",
    "官网统一使用“合规工具 / Compliance tools”作为计算器、快速核对和估算入口的公开名称。内部技术字段仍保留 `tool_route`，避免为了文案改名破坏接口兼容性。`cn_code_lookup` 也只是内部意图路由键，不表示系统能自动查询或认定编码。顾问中的 CN Code 路径显示为“推荐合规工具”。",
    "",
    "## 完整路径图",
    "",
    "下图用于核对路径结构；每个选择对应的具体答案、资料和 CTA 见后文逐项表。",
    "",
    "```mermaid",
    "flowchart LR",
    "  START([进入官网，顾问自动展开]) --> TOPICS{选择预制问题}",
  );

  for (const record of catalog.fixedAnswers) {
    const topic = catalog.topics.find((item) => item.id === record.topicId);
    const tid = `T_${nodeId(record.topicId)}`;
    const end = `E_${nodeId(record.topicId)}`;
    lines.push(`  TOPICS --> ${tid}[\"${mermaid(topic?.label.zh || record.topicId)}\"]`);
    lines.push(`  ${end}([\"专属固定答案 + 资料 + CTA\"])`);
    for (const option of record.suggestedReplies || []) {
      const rid = `R_${nodeId(record.topicId)}_${nodeId(option.id)}`;
      lines.push(`  ${tid} --> ${rid}[\"${mermaid(option.label.zh)}\"] --> ${end}`);
    }
  }
  lines.push("  FREE[用户自由输入] --> CN{命中 CN / HS / TARIC 意图?}");
  lines.push("  CN -->|是| TOOL[CN Code 合规工具说明 + 试算器 + 编码指南 + 人工复核]");
  lines.push("  CN -->|否| RETRIEVAL[受控检索 / 模型回答或安全兜底]");
  lines.push("```", "", "## 逐项答案核对", "");

  for (const record of catalog.fixedAnswers) {
    const topic = catalog.topics.find((item) => item.id === record.topicId);
    lines.push(`<a id="path-${record.topicId}"></a>`, "", `### ${topic?.label.zh || record.topicId}`, "");
    lines.push(`- 路径 ID：\`${record.topicId}\``);
    lines.push(`- 一级默认答案：${record.answer.zh}`);
    lines.push(`- 追问：${record.nextQuestion.zh}`);
    lines.push(`- 资料：${(record.sourceIds || []).map((id) => `\`${id}\``).join("、")}`);
    lines.push(`- CTA：${record.cta.label.zh}（\`${record.cta.url}\`）`);
    lines.push("- 继承规则：下列每条二级答案均使用本节资料与 CTA。", "");
    lines.push("| 用户选择 | Reply ID | 对应默认答案 |", "|---|---|---|");
    for (const option of record.suggestedReplies || []) {
      const outcome = catalog.replyOutcomes?.[record.topicId]?.[option.id];
      if (!outcome) throw new Error(`Missing outcome: ${record.topicId}.${option.id}`);
      lines.push(`| ${md(option.label.zh)} | \`${option.id}\` | ${md(outcome.zh)} |`);
    }
    lines.push("");
  }

  lines.push(
    "## CN Code 合规工具直达路径",
    "",
    "- 概念：HS 通常指国际协调制度的 6 位基础编码；CN 是欧盟 8 位商品编码；TARIC 在 CN 基础上叠加欧盟具体措施。实际申报仍以进口方与海关适用口径为准。",
    "- 能力边界：本路径只支持从已有列表选择编码进行试算、阅读核对方法或申请人工复核，不根据产品描述自动查询、生成或正式认定 CN Code。",
    "",
  );
  for (const route of catalog.toolRoutes) {
    lines.push(`- 内部路由键：\`${route.intent}\``);
    lines.push(`- 默认答案：${route.answer.zh}`);
    lines.push(`- 三个入口：${route.links.map((item) => `${linkTypeName[item.type] || item.type}：${item.label.zh}（\`${item.url}\`）`).join("；")}`);
    lines.push(`- 资料：${(route.sourceIds || []).map((id) => `\`${id}\``).join("、")}`, "");
  }

  lines.push(
    "## 当前审计结果",
    "",
    `- 一级固定答案：${catalog.fixedAnswers.length}/${catalog.fixedAnswers.length} 条具备中英文、来源与 CTA。`,
    `- 二级确定性答案：${replyCount}/${replyCount} 条具备中英文，缺失 0 条。`,
    `- CN Code 意图路径：${catalog.toolRoutes.length}/${catalog.toolRoutes.length} 条，包含合规工具、知识指南和人工复核三个入口。`,
    "- 运行时约束：所有预制问题与二级选择均返回 `fixed`；CN Code 路径返回 `tool_route`；二者均不进入模型调用。",
    "- 文档约束：`node scripts/generate-advisor-preset-audit.cjs --check` 必须通过。",
    "",
    "## 完整性门槛",
    "",
    "发布前必须同时满足：",
    "",
    "1. 每个一级问题都有中英文固定答案、追问、资料和 CTA。",
    "2. 每个可见二级选择都有独立的中英文默认答案，不允许使用统一的“已记录”占位话术。",
    "3. 所有预制路径的响应模式均为 `fixed`，并在本地完成，不进入模型调用。",
    "4. 每个二级选择都是有资料与 CTA 的终点，不出现空节点或死路。",
    "5. CN Code 相关意图优先返回现有合规工具与核对指南，不由模型作出正式归类认定。",
    "6. 本文件必须由目录重新生成并通过 `--check`，避免文档与运行时内容漂移。",
    ""
  );
  return lines.join("\n");
}

const generated = buildDocument();
if (process.argv.includes("--write")) {
  fs.writeFileSync(outputPath, generated, "utf8");
  console.log(`Wrote ${path.relative(root, outputPath)}`);
} else if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error("Advisor preset audit is out of date. Run: node scripts/generate-advisor-preset-audit.cjs --write");
    process.exit(1);
  }
  console.log("Advisor preset audit is current.");
} else {
  process.stdout.write(generated);
}
